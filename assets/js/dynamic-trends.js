function utcTs(iso) { const [y, m, d] = iso.split('-').map(Number); return Date.UTC(y, m - 1, d); }

// Same definitions as the Admin publisher (QuantStats, 365-day annualisation,
// risk-free 0): cagr, volatility, max drawdown, Sharpe, Sortino.
function windowMetrics(pts) {
  const v = pts.map(p => p.fund);
  const r = [];
  for (let i = 1; i < v.length; i++) r.push(v[i] / v[i - 1] - 1);
  const n = r.length;
  if (n < 2) return {};
  const mean = r.reduce((a, b) => a + b, 0) / n;
  const sd = Math.sqrt(r.reduce((a, b) => a + (b - mean) ** 2, 0) / (n - 1));
  const down = Math.sqrt(r.reduce((a, b) => a + (b < 0 ? b * b : 0), 0) / n);
  const years = (utcTs(pts[pts.length - 1].date) - utcTs(pts[0].date)) / 86400000 / 365;
  let acc = 1, peak = 1, mdd = 0;
  for (const x of r) { acc *= 1 + x; peak = Math.max(peak, acc); mdd = Math.min(mdd, acc / peak - 1); }
  return {
    cagr: Math.pow(v[v.length - 1] / v[0], 1 / years) - 1,
    volatility: sd * Math.sqrt(365),
    maxDrawdown: mdd,
    sharpe: mean / sd * Math.sqrt(365),
    sortino: mean / down * Math.sqrt(365),
  };
}

